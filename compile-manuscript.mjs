import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

export function parseManuscript(source) {
  const sections = [];
  let part = null;
  let current = null;
  for (const block of source.replace(/\r\n/g, '\n').trim().split(/\n\s*\n/)) {
    const partHeading = block.match(/^# Part (I|II|III) — (.+)$/);
    const sequenceHeading = block.match(/^## (\d{2}) — (.+)$/);
    if (partHeading) {
      part = ['I', 'II', 'III'].indexOf(partHeading[1]);
      current = null;
    } else if (sequenceHeading) {
      current = { number: Number(sequenceHeading[1]), title: sequenceHeading[2], part, blocks: [] };
      sections.push(current);
    } else if (block === '---' || /^## Editorial and factual review notes/.test(block)) {
      current = null;
    } else if (current && !/^\*\*(?:Visual direction|Interaction|Closing visual):\*\*/.test(block)) {
      current.blocks.push(block);
    }
  }
  const expectedNumbers = Array.from({ length: 17 }, (_, index) => index + 1)
    .filter(number => sections.length === 17 || number !== 2);
  const numbers = new Set(sections.map(section => section.number));
  if (![16, 17].includes(sections.length) || numbers.size !== sections.length ||
      expectedNumbers.some(number => !numbers.has(number)) ||
      sections.some((section, index) => section.part === null || !section.blocks.length || index > 0 && section.part < sections[index - 1].part))
    throw new Error('Expected the complete approved manuscript with unique stable sequence IDs in reading-part order.');
  return sections;
}

export function compileManuscript(source) {
  return `// Generated by compile-manuscript.mjs. Edit only the approved Markdown source.\nexport const manuscriptSha256 = ${JSON.stringify(createHash('sha256').update(source).digest('hex'))};\nexport const manuscriptSections = ${JSON.stringify(parseManuscript(source), null, 2)};\n`;
}

export function parseAtticaTimeline(source) {
  const blocks = source.replace(/\r\n/g, '\n').trim().split(/\n\s*\n/);
  const heading = title => {
    const index = blocks.indexOf(`## ${title}`);
    if (index < 0) throw new Error(`Missing approved Attica heading: ${title}`);
    const paragraphs = [];
    for (const block of blocks.slice(index + 1)) {
      if (block.startsWith('#')) break;
      paragraphs.push(block);
    }
    return { title, paragraphs };
  };
  const metadata = name => {
    const block = blocks.find(block => block.startsWith(`**${name}:** `));
    if (!block) throw new Error(`Missing Attica chart ${name}`);
    return block.slice(`**${name}:** `.length);
  };
  const json = blocks.find(block => block.startsWith('```json\n'));
  if (!json) throw new Error('Missing integer-minute Attica chart data.');
  const rows = JSON.parse(json.slice(8, -4));
  if (rows.length !== 7 || rows.some(row => !row.label || !row.group ||
    !Number.isSafeInteger(row.activationToAcquisitionMin) || row.activationToAcquisitionMin <= 0 ||
    !Number.isSafeInteger(row.acquisitionToProductMin) || row.acquisitionToProductMin <= 0))
    throw new Error('Expected seven positive integer-minute Attica records.');
  const groups = blocks.filter(block => block.startsWith('#### Group ')).map(block => block.slice(5));
  const tableRows = blocks.filter(block => block.startsWith('| Product |') || block.startsWith('| Case and instrument |'))
    .flatMap(block => block.split('\n').slice(2).map(line => line.split('|').slice(1, -1).map(cell => cell.trim())));
  if (groups.length !== 2 || tableRows.length !== rows.length) throw new Error('Incomplete Attica source tables.');
  return {
    title: blocks[0].slice(2),
    introduction: heading('The Satellite Is Only Part of the Waiting Time'),
    interpretation: heading('What These Delays Tell Us'),
    transition: heading('What If Meridian Had Planned the Mission?'),
    chartHeading: blocks.find(block => block.startsWith('### Interactive figure')).slice(4),
    chartTitle: metadata('Chart title'), chartSubtitle: metadata('Chart subtitle'),
    groups, rows, tableRows,
    figureNote: blocks.find(block => block.startsWith('*Figure note:')).slice(1, -1),
    evidenceHeading: 'Sources and evidence notes',
    evidence: blocks.slice(blocks.indexOf('### Sources and evidence notes') + 1).join('\n\n').split('\n').map(line => line.replace(/^- /, '')),
  };
}

export function compileAtticaTimeline(source) {
  return `// Generated by compile-manuscript.mjs. Edit only the approved Attica Markdown.\nexport const atticaTimelineSha256 = ${JSON.stringify(createHash('sha256').update(source).digest('hex'))};\nexport const atticaTimeline = ${JSON.stringify(parseAtticaTimeline(source), null, 2)};\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const source = await readFile(new URL('./content/agentic-earth-observation-manuscript-v3.md', import.meta.url), 'utf8');
  const target = new URL('./manuscript-data.js', import.meta.url);
  const compiled = compileManuscript(source);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== compiled) throw new Error('Compiled manuscript differs from the approved Markdown. Run node compile-manuscript.mjs.');
    console.log('Approved manuscript and compiled reading text match exactly.');
  } else {
    await writeFile(target, compiled);
    console.log('Compiled the approved manuscript without rewriting its prose.');
  }
  const atticaSource = await readFile(new URL('./content/attica-timeline-chapter.md', import.meta.url), 'utf8');
  const atticaTarget = new URL('./attica-timeline-data.js', import.meta.url);
  const atticaCompiled = compileAtticaTimeline(atticaSource);
  if (process.argv.includes('--check')) {
    if (await readFile(atticaTarget, 'utf8') !== atticaCompiled) throw new Error('Compiled Attica chapter differs from the approved Markdown. Run node compile-manuscript.mjs.');
    console.log('Approved Attica chapter and integer-minute chart data match exactly.');
  } else {
    await writeFile(atticaTarget, atticaCompiled);
    console.log('Compiled the approved Attica chapter without rewriting its prose.');
  }
}
