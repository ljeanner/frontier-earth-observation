import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

export function parseManuscript(source) {
  const sections = [];
  let part = null;
  let current = null;
  for (const block of source.replace(/\r\n/g, '\n').trim().split(/\n\s*\n/)) {
    const partHeading = block.match(/^# Part (I|II|III) — (.+)$/);
    const sequenceHeading = block.match(/^## (\d{2}) — (.+)$/);
    if (partHeading) {
      part = ['I', 'II', 'III'].indexOf(partHeading[1]);
      current = null;
    } else if (sequenceHeading) {
      current = { number: Number(sequenceHeading[1]), title: sequenceHeading[2], part, blocks: [] };
      sections.push(current);
    } else if (block === '---' || /^## Editorial and factual review notes/.test(block)) {
      current = null;
    } else if (current && !/^\*\*(?:Visual direction|Interaction|Closing visual):\*\*/.test(block)) {
      current.blocks.push(block);
    }
  }
  const expectedNumbers = Array.from({ length: 17 }, (_, index) => index + 1)
    .filter(number => sections.length === 17 || number !== 2);
  const numbers = new Set(sections.map(section => section.number));
  if (![16, 17].includes(sections.length) || numbers.size !== sections.length ||
      expectedNumbers.some(number => !numbers.has(number)) ||
      sections.some((section, index) => section.part === null || !section.blocks.length || index > 0 && section.part < sections[index - 1].part))
    throw new Error('Expected the complete approved manuscript with unique stable sequence IDs in reading-part order.');
  return sections;
}

export function compileManuscript(source) {
  return `// Generated by compile-manuscript.mjs. Edit only the approved Markdown source.\nexport const manuscriptSha256 = ${JSON.stringify(createHash('sha256').update(source).digest('hex'))};\nexport const manuscriptSections = ${JSON.stringify(parseManuscript(source), null, 2)};\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const source = await readFile(new URL('./content/agentic-earth-observation-manuscript-v3.md', import.meta.url), 'utf8');
  const target = new URL('./manuscript-data.js', import.meta.url);
  const compiled = compileManuscript(source);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== compiled) throw new Error('Compiled manuscript differs from the approved Markdown. Run node compile-manuscript.mjs.');
    console.log('Approved manuscript and compiled reading text match exactly.');
  } else {
    await writeFile(target, compiled);
    console.log('Compiled the approved manuscript without rewriting its prose.');
  }
}
